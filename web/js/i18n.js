let LANG = pickLang();
/** Language: ?lang=xx (passed by the app) > choice saved in Settings > browser language; English if no translation. */
function pickLang() {
  let saved = '';
  try { saved = localStorage.getItem('camerold-lang') || ''; } catch {}
  const want = (new URLSearchParams(location.search).get('lang') || saved || navigator.language || 'en').toLowerCase();
  const keys = Object.keys(I18N), base = want.split('-')[0];
  // Exact tag (pt-br), then the same language (pt-br -> pt, or pt -> pt-BR), else English
  return keys.find(k => k.toLowerCase() === want) || keys.find(k => k.toLowerCase() === base) ||
    keys.find(k => k.toLowerCase().split('-')[0] === base) || 'en';
}

function t(key, vars) {
  let s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => vars[k]);
  return s;
}

/** Fills text for elements with data-i18n (content), data-i18n-html, data-i18n-ph (placeholder), data-i18n-label (aria-label + title). */
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-label]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nLabel)); el.title = t(el.dataset.i18nLabel); });
}
